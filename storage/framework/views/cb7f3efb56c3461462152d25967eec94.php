<script>
    document.addEventListener('DOMContentLoaded', function() {

        // ── Program Tab Switching ──
        const tabBtns = document.querySelectorAll('.tab-btn');
        const programItems = document.querySelectorAll('.program-item');
        const emptyState = document.getElementById('empty-program-msg');

        // Initial filter on page load based on active tab
        const activeTab = document.querySelector('.tab-btn.active');
        if (activeTab) {
            filterPrograms(activeTab.getAttribute('data-category'));
        }

        tabBtns.forEach(btn => {
            btn.addEventListener('click', function() {
                tabBtns.forEach(b => b.classList.remove('active'));
                this.classList.add('active');
                
                const category = this.getAttribute('data-category');
                filterPrograms(category);
            });
        });

        function filterPrograms(category) {
            let hasVisible = false;
            programItems.forEach(item => {
                const itemCategory = item.getAttribute('data-program-category');
                if (itemCategory === category) {
                    item.style.display = '';
                    hasVisible = true;
                } else {
                    item.style.display = 'none';
                }
            });

            if (emptyState) {
                emptyState.style.display = hasVisible ? 'none' : 'block';
            }
        }

        // ── Search ──
        const searchInput = document.getElementById('search-input');
        const btnSearch   = document.getElementById('btn-search');
        if (btnSearch) {
            btnSearch.addEventListener('click', function() {
                const query = searchInput.value.trim();
                if (query) window.location.href = '<?php echo e(url("/search")); ?>?q=' + encodeURIComponent(query);
            });
        }
        if (searchInput) {
            searchInput.addEventListener('keypress', function(e) {
                if (e.key === 'Enter') btnSearch.click();
            });
        }

        // ── Smooth scroll dengan offset navbar ──
        // Offset tinggi navbar sticky (~72px)
        const NAVBAR_HEIGHT = 72;
        document.querySelectorAll('a[href*="#"]').forEach(link => {
            link.addEventListener('click', function(e) {
                const href = this.getAttribute('href');
                const hashIndex = href.indexOf('#');
                if (hashIndex === -1) return;

                const targetId = href.substring(hashIndex + 1);
                const target   = document.getElementById(targetId);
                if (!target) return;

                // Jika anchor di halaman yang sama, scroll mulus
                const linkPath = href.substring(0, hashIndex) || window.location.pathname;
                const isSamePage = linkPath === window.location.pathname
                                || linkPath === '/'
                                || linkPath === '';
                if (isSamePage) {
                    e.preventDefault();
                    const top = target.getBoundingClientRect().top + window.scrollY - NAVBAR_HEIGHT - 8;
                    window.scrollTo({ top, behavior: 'smooth' });
                }
            });
        });

        // ── Scroll Spy: highlight menu aktif saat scroll ──
        const sections = [
            { id: 'hero-section',    nav: 'nav-beranda' },
            { id: 'tentang-section', nav: 'nav-tentang'  },
            { id: 'program-section', nav: 'nav-program'  },
            { id: 'berita-section',  nav: 'nav-berita'   },
            { id: 'laporan-section', nav: 'nav-laporan'  },
        ];

        function updateActiveNav() {
            const scrollY = window.scrollY + NAVBAR_HEIGHT + 20;
            let current  = sections[0].nav;

            sections.forEach(({ id }) => {
                const el = document.getElementById(id);
                if (el && el.offsetTop <= scrollY) {
                    current = sections.find(s => s.id === id).nav;
                }
            });

            sections.forEach(({ nav }) => {
                const link = document.getElementById(nav);
                if (link) link.classList.toggle('active', nav === current);
            });
        }

        window.addEventListener('scroll', updateActiveNav, { passive: true });
        updateActiveNav();

        // ── Jika halaman dibuka dengan hash, scroll ke sana ──
        if (window.location.hash) {
            const targetId = window.location.hash.substring(1);
            const target   = document.getElementById(targetId);
            if (target) {
                setTimeout(() => {
                    const top = target.getBoundingClientRect().top + window.scrollY - NAVBAR_HEIGHT - 8;
                    window.scrollTo({ top, behavior: 'smooth' });
                }, 100);
            }
        }
    });
</script>
